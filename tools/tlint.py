COMPILED = [(i, re.compile(p), cap, label, fix) for i, p, cap, label, fix in RULES]

# 코퍼스 전체에서 이 구문이 나올 수 있는 블록의 최대 비율. 한 블록에 한 번씩이라도 수천 개 블록 곳곳에 흩어지면 글 전체가
# 번역투로 읽히므로, 한 블록의 cap 과 별도로 전체 비율을 제한한다. 적히지 않은 규칙은 cap 만 본다.
QUOTA = {
    "A-12": 0.005, "A-20": 0.003,
    "L-2": 0.015, "L-3": 0.04, "L-4": 0.03, "L-5": 0.02, "L-6": 0.015, "L-7": 0.015, "L-8": 0.01,
    "L-10": 0.01, "L-11": 0.02, "L-12": 0.14, "L-14": 0.015, "L-15": 0.01, "L-16": 0.01,
}
# L-12(~것입니다 류 결말)는 한국어 설명문에서 흔한 끝맺음이라 한 블록에 한 번은 허용하고, 전체 비율만 넉넉히 14% 로 둔다.
# 고치기 전 해설은 22.6%(1976블록 중 447) 였고 고친 뒤 13.2%(261)다.
# 한 번도 허용하지 않는 규칙(cap 0)도 코퍼스에서는 0 이다.
for _rid, _rx, _cap, _l, _f in RULES:
    if _cap == 0:
        QUOTA.setdefault(_rid, 0.0)


def mask(t: str) -> str:
    """따옴표 안(성경 구절 인용)은 점검하지 않는다."""
    return re.sub(r'"[^"\n]*"|“[^”\n]*”|「[^」\n]*」|`[^`\n]*`', lambda m: " " * len(m.group(0)), t)


def blocks_with(rule_id: str, texts) -> list:
    """texts 중 rule_id 구문이 한 번이라도 나오는 것의 색인."""
    rx = next(r for i, r, *_ in COMPILED if i == rule_id)
    return [k for k, tx in enumerate(texts) if rx.search(mask(tx))]


def corpus_check(texts) -> list:
    """코퍼스 단위 점검. 허용 비율을 넘는 규칙 [(id, 라벨, 나온 블록 수, 허용 블록 수)]."""
    n = len(texts)
    over = []
    for rid, _rx, _cap, label, _fix in COMPILED:
        q = QUOTA.get(rid)
        if q is None:
            continue
        have = len(blocks_with(rid, texts))
        if have > int(n * q):
            over.append((rid, label, have, int(n * q)))
    return over


def check_block(text: str) -> list:
    """한 블록의 번역투 hit 목록 [(id, 라벨, 걸린 말, 고치는 방향)]. cap 이하면 허용."""
    t = mask(text)
    hits = []
    for rid, rx, cap, label, fix in COMPILED:
        found = [m.group(0).strip() for m in rx.finditer(t)]
        if len(found) > cap:
            hits.extend((rid, label, f, fix) for f in found)
    return hits


def main(argv):
    import json
    from collections import Counter
    from pathlib import Path
    path = Path(__file__).resolve().parent.parent / "data" / "plan.json"
    show = int(argv[argv.index("--show") + 1]) if "--show" in argv else 0
    plan = json.loads(path.read_text(encoding="utf-8"))
    per_rule, blocks_hit, texts, shown = Counter(), 0, [], 0
    for d in plan["days"]:
        for k, b in enumerate(d["blocks"]):
            texts.append(b["text"])
            h = check_block(b["text"])
            if h:
                blocks_hit += 1
                if shown < show:
                    shown += 1
                    print(f"{d['day']}일 {k + 1}번째 블록: " + ", ".join(f"{x[2]}({x[0]})" for x in h))
            for rid in {x[0] for x in h}:
                per_rule[rid] += 1
    print(f"블록 {len(texts)}개 중 한 블록의 허용 횟수를 넘은 블록 {blocks_hit}개")
    labels = {i: label for i, _, _, label, _ in RULES}
    for rid, n in per_rule.most_common():
        print(f"  {rid:5s} {n:4d}블록  {labels[rid]}")
    over = corpus_check(texts)
    for rid, label, have, allow in over:
        print(f"전체 비율 초과 {rid} {label}: {have}블록 (허용 {allow})")
    return 1 if blocks_hit or over else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
