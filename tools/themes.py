def problems_of(entry: dict) -> list:
    """후보 하나의 주제 문제. 주제가 없으면 문제가 아니다(옛 후보)."""
    th = entry.get("theme")
    if th is None:
        return []
    if th not in THEMES.get(entry.get("category"), []):
        return [f"{entry.get('id')}: 주제 '{th}' 는 범주 '{entry.get('category')}' 의 목록에 없습니다"]
    return []


def window_problems(scenes: dict, window: int = WINDOW, cap: int = CAP) -> list:
    """같은 범주의 같은 주제가 어느 window 일 안에서도 cap 번을 넘지 않는지 본다."""
    by = defaultdict(list)
    for day, s in scenes.items():
        th = s.get("theme")
        if th and th != OTHER and s.get("category"):
            by[(s["category"], th)].append(int(day))
    out = []
    for (cat, th), days in sorted(by.items()):
        days.sort()
        i = 0
        while i < len(days):
            span = [d for d in days[i:] if d < days[i] + window]
            if len(span) > cap:
                out.append(f"{days[i]}일부터 {window}일 안에 범주 '{cat}' 의 주제 '{th}' 가 {len(span)}번입니다(상한 {cap}): {', '.join(map(str, span))}일")
                i += len(span)         # 같은 덩어리를 두 번 알리지 않는다
            else:
                i += 1
    return out
